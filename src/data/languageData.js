// ========================================================
// FIND DISEASE MATCH
// ========================================================

export function findDiseaseMatch(question) {

    let matchKey = null;
    let bestScore = 0;

    for (const key in DISEASE_INFO) {

        const info =
            DISEASE_INFO[key];

        const searchable =
            (
                info.name +
                " " +
                info.cropFamily
            ).toLowerCase();

        const terms =
            searchable
                .split(/[\s-]+/)
                .filter(
                    term => term.length > 3
                );

        const score =
            terms.filter(
                term =>
                    question.includes(term)
            ).length;

        if (score > bestScore) {

            bestScore = score;
            matchKey = key;

        }
    }

    return matchKey;
}